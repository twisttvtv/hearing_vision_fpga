// 功能：FPGA通过SCCB总线向OV5640写一个寄存器。

// 一次完整写操作：
//
//      START
//        ↓
//      8'h78              OV5640写地址
//        ↓ ACK
//      reg_addr[15:8]     寄存器地址高8位
//        ↓ ACK
//      reg_addr[7:0]      寄存器地址低8位
//        ↓ ACK
//      reg_data           要写入的数据
//        ↓ ACK
//      STOP
//
// OV5640的SCCB写地址为8'h78。
//============================================================

`timescale 1ns/1ps

module model_sccb_write(

    input  wire        clk,          // FPGA系统时钟，100MHz
    input  wire        rst_n,        // 低电平复位
    input  wire        start,        // 拉高1拍，开始一次写寄存器操作
    input  wire [15:0] reg_addr,     // OV5640寄存器地址
    input  wire [7:0]  reg_data,     // 要写入寄存器的数据

    output reg         busy,         // =1：当前正在进行SCCB通信
    output reg         done,         // =1：一次寄存器写操作完成，只保持1拍

    inout  wire        cam_scl,      // SCCB时钟线
    inout  wire        cam_sda       // SCCB数据线

);


//============================================================
// 1. SCCB开漏控制
//============================================================
// SCCB/I2C总线不是直接输出高电平。
//
// scl_drive_low = 1：
// FPGA主动把SCL拉低
//
// scl_drive_low = 0：
// FPGA松开SCL，输出高阻Z
// 外部上拉电阻把SCL拉成高电平
//
// SDA同理。
//============================================================

reg scl_drive_low;
reg sda_drive_low;


// FPGA只负责：
// 1. 拉低
// 2. 松开
assign cam_scl = scl_drive_low ? 1'b0 : 1'bz;
assign cam_sda = sda_drive_low ? 1'b0 : 1'bz;


//============================================================
// 2. 产生SCCB操作节拍
//============================================================
// FPGA时钟：100MHz
//
// 每250个clk产生一个sccb_tick：
//
// 100MHz / 250 = 400kHz
//
// 后面一个完整SCL周期分成4个phase，
// 因此最终SCL约为：
//
// 400kHz / 4 = 100kHz
//============================================================

reg [7:0] div_cnt;
reg       sccb_tick;


always @(posedge clk or negedge rst_n) begin

    if(!rst_n) begin

        div_cnt   <= 8'd0;
        sccb_tick <= 1'b0;

    end

    else if(!busy) begin

        div_cnt   <= 8'd0;
        sccb_tick <= 1'b0;

    end

    else begin

        if(div_cnt == 8'd249) begin

            // 数到249以后重新从0开始
            div_cnt <= 8'd0;

            // 产生一个clk宽度的操作脉冲
            sccb_tick <= 1'b1;

        end

        else begin

            div_cnt <= div_cnt + 1'b1;

            // 其他时间tick保持0
            sccb_tick <= 1'b0;

        end

    end

end


//============================================================
// 3. 状态定义
//============================================================
//
// 整个写寄存器过程需要经过：
// IDLE
//   ↓
// START
//   ↓
// SEND BYTE
//   ↓
// ACK
//   ↓
// SEND BYTE
//   ↓
// ...
//   ↓
// STOP
//   ↓
// IDLE
//
// STOP拆成三个状态，目的是产生正确的停止条件：
// STOP0：SCL=0，SDA=0
// STOP1：SCL=1，SDA=0
// STOP2：SCL=1，SDA=1
//
// SDA在SCL为高时从0变1，就是STOP。
//============================================================

localparam STATE_IDLE   = 3'd0;
localparam STATE_START  = 3'd1;
localparam STATE_SEND   = 3'd2;
localparam STATE_ACK    = 3'd3;
localparam STATE_STOP0  = 3'd4;
localparam STATE_STOP1  = 3'd5;
localparam STATE_STOP2  = 3'd6;

reg [2:0] state;

//============================================================
// 4. 发送数据需要的变量
//============================================================
// 当前正在发送的一个8bit数据
reg [7:0] tx_shift;

// 当前发送的是这个字节的第几个bit
// 0 ~ 7
reg [2:0] bit_cnt;

// 当前正在发送的那个bit
// SCCB从最高位bit7开始发送
wire tx_bit;

assign tx_bit = tx_shift[7];


//------------------------------------------------------------
// byte_cnt：当前正在发送第几个字节
//
// byte_cnt = 0：8'h78
// byte_cnt = 1：reg_addr[15:8]
// byte_cnt = 2：reg_addr[7:0]
// byte_cnt = 3：reg_data
//------------------------------------------------------------
reg [1:0] byte_cnt;

//------------------------------------------------------------
// 保存寄存器地址和数据
// start来的时候先把它们保存下来。
// 这样即使外面的camera_init之后修改reg_addr/reg_data，
// 当前这次SCCB通信也不会受到影响。
//------------------------------------------------------------

reg [15:0] reg_addr_latch;
reg [7:0]  reg_data_latch;


//------------------------------------------------------------
// ACK相关
//------------------------------------------------------------

// =1：当前处于ACK阶段
// 这里主要保留这个变量方便理解和以后观察波形
reg wait_ack;


// =1：本次ACK正确
// =0：没有收到ACK
reg ack_ok;


//------------------------------------------------------------
// START状态标志
// 也是为了让代码含义更直观。
//------------------------------------------------------------

reg start_cond;


//============================================================
// 5. 一个SCL周期拆成4个阶段
//============================================================
//
// phase 0：SCL低
//          FPGA准备SDA
//
// phase 1：SCL变高
//
// phase 2：SCL保持高
//          OV5640读取SDA
//          或FPGA读取ACK
//
// phase 3：SCL重新变低
//          当前这一位结束
//
// 波形大概：
//
// phase      0      1      2      3
//
// SCL        0      1      1      0
//
//============================================================

reg [1:0] sccb_phase;


always @(posedge clk or negedge rst_n) begin

    if(!rst_n) begin

        sccb_phase <= 2'd0;

    end

    // 只有发送数据或者读取ACK时，
    // 才需要让phase不断0→1→2→3
    else if((state == STATE_SEND || state == STATE_ACK)
            && sccb_tick) begin

        sccb_phase <= sccb_phase + 1'b1;

    end

    // 其他状态phase回到0
    else if(state != STATE_SEND && state != STATE_ACK) begin

        sccb_phase <= 2'd0;

    end

    // 没有新的tick时保持原来的phase
    else begin

        sccb_phase <= sccb_phase;

    end

end


//============================================================
// 6. 控制SCL 
//============================================================
// SCL低的时候：
// FPGA可以修改SDA

// SCL高的时候：
// OV5640读取SDA

always @(*) begin

    // 默认松开SCL
    //
    // FPGA输出Z
    // 外部上拉电阻把SCL拉高
    scl_drive_low = 1'b0;

    case(state)

        //----------------------------------------------------
        // 空闲
        //
        // SCL保持高电平
        //----------------------------------------------------
        STATE_IDLE: begin

            scl_drive_low = 1'b0;

        end


        //----------------------------------------------------
        // START
        // START要求：
        // SCL保持高
        // SDA从高变低
        //----------------------------------------------------
        STATE_START: begin

            scl_drive_low = 1'b0;

        end


        //----------------------------------------------------
        // 正常发送数据
        //----------------------------------------------------
        STATE_SEND: begin

            case(sccb_phase)

                2'd0:
                    scl_drive_low = 1'b1;   // SCL低

                2'd1:
                    scl_drive_low = 1'b0;   // SCL高

                2'd2:
                    scl_drive_low = 1'b0;   // SCL继续保持高

                2'd3:
                    scl_drive_low = 1'b1;   // SCL重新拉低

                default:
                    scl_drive_low = 1'b0;

            endcase

        end

        //----------------------------------------------------
        // ACK同样需要一个完整SCL周期
        //----------------------------------------------------
        STATE_ACK: begin

            case(sccb_phase)

                2'd0:
                    scl_drive_low = 1'b1;

                2'd1:
                    scl_drive_low = 1'b0;

                2'd2:
                    scl_drive_low = 1'b0;

                2'd3:
                    scl_drive_low = 1'b1;

                default:
                    scl_drive_low = 1'b0;

            endcase

        end

        //----------------------------------------------------
        // STOP第1步
        //
        // SCL低
        // SDA低
        //----------------------------------------------------
        STATE_STOP0: begin

            scl_drive_low = 1'b1;

        end


        //----------------------------------------------------
        // STOP第2步
        //
        // SCL变高
        // SDA仍然保持低
        //----------------------------------------------------
        STATE_STOP1: begin

            scl_drive_low = 1'b0;

        end


        //----------------------------------------------------
        // STOP第3步
        //
        // SCL高
        // SDA从低变高
        //----------------------------------------------------
        STATE_STOP2: begin

            scl_drive_low = 1'b0;

        end

        default: begin
            scl_drive_low = 1'b0;
        end
    endcase

end


//============================================================
// 7. 控制SDA
//============================================================
always @(*) begin
    // 默认松开SDA
    sda_drive_low = 1'b0;

    case(state)
        //----------------------------------------------------
        // IDLE
        //
        // SDA松开
        // 外部上拉以后SDA=1
        //----------------------------------------------------
        STATE_IDLE: begin

            sda_drive_low = 1'b0;

        end

        //----------------------------------------------------
        // START
        //
        // SCL为高的时候
        // FPGA主动把SDA拉低
        //
        // SDA：1 → 0
        //----------------------------------------------------
        STATE_START: begin

            sda_drive_low = 1'b1;

        end

        //----------------------------------------------------
        // SEND
        //
        // tx_bit = 0：
        //     FPGA主动拉低SDA
        //
        // tx_bit = 1：
        //     FPGA松开SDA
        //     外部上拉成高电平
        //----------------------------------------------------
        STATE_SEND: begin

            sda_drive_low = ~tx_bit;

        end

        //----------------------------------------------------
        // ACK
        //
        // FPGA必须松开SDA
        // 让OV5640来控制SDA
        //----------------------------------------------------
        STATE_ACK: begin

            sda_drive_low = 1'b0;
        end

        //----------------------------------------------------
        // STOP0
        //
        // SDA保持低
        //----------------------------------------------------
        STATE_STOP0: begin
            sda_drive_low = 1'b1;
        end

        //----------------------------------------------------
        // STOP1
        //
        // SCL已经变高
        // 但是SDA继续保持低
        //----------------------------------------------------
        STATE_STOP1: begin
            sda_drive_low = 1'b1;

        end

        //----------------------------------------------------
        // STOP2
        //
        // 松开SDA
        // SDA被上拉到高电平
        //
        // 因此：
        // SCL高的时候 SDA：0 → 1
        //
        // 产生STOP
        //----------------------------------------------------
        STATE_STOP2: begin

            sda_drive_low = 1'b0;

        end

        default: begin

            sda_drive_low = 1'b0;
        end

    endcase

end


//============================================================
// 8. SCCB主控制状态机
//============================================================

always @(posedge clk or negedge rst_n) begin

    if(!rst_n) begin

        state <= STATE_IDLE;

        busy <= 1'b0;
        done <= 1'b0;

        tx_shift <= 8'd0;

        bit_cnt  <= 3'd0;
        byte_cnt <= 2'd0;

        reg_addr_latch <= 16'd0;
        reg_data_latch <= 8'd0;

        wait_ack  <= 1'b0;
        ack_ok    <= 1'b0;
        start_cond <= 1'b0;

    end

    else begin

        //----------------------------------------------------
        // done只保持一个FPGA系统时钟周期
        //----------------------------------------------------
        done <= 1'b0;


        case(state)

            //================================================
            // IDLE
            //================================================
            STATE_IDLE: begin

                busy       <= 1'b0;
                wait_ack   <= 1'b0;
                start_cond <= 1'b0;


                //------------------------------------------------
                // 收到start，开始一次新的写寄存器操作
                //------------------------------------------------
                if(start) begin

                    busy <= 1'b1;

                    // 保存当前要写的寄存器地址和数据
                    reg_addr_latch <= reg_addr;
                    reg_data_latch <= reg_data;

                    // 第一个字节从0开始
                    byte_cnt <= 2'd0;

                    // 一个字节从第一个bit开始
                    bit_cnt <= 3'd0;

                    // 第一个发送的数据：
                    // OV5640 SCCB写地址 = 8'h78
                    tx_shift <= 8'h78;

                    // 接下来先产生START
                    start_cond <= 1'b1;

                    state <= STATE_START;

                end

            end


            //================================================
            // START
            //================================================
            //
            // 此时组合逻辑保证：
            //
            // SCL = 高
            // SDA = 低
            //
            // START保持一个sccb_tick以后，
            // 开始发送第一个字节8'h78。
            //================================================
            STATE_START: begin

                busy <= 1'b1;

                if(sccb_tick) begin

                    start_cond <= 1'b0;

                    state <= STATE_SEND;

                end

            end


            //================================================
            // SEND
            //================================================
            //
            // 每个字节发送8bit。
            //
            // tx_shift[7]永远作为当前发送bit。
            //
            // 当前bit在phase3完成以后：
            //
            // tx_shift左移
            // bit_cnt + 1
            //
            // 第8bit结束以后进入ACK。
            //================================================
            STATE_SEND: begin

                busy <= 1'b1;


                // 当前一个bit已经完整发送完成
                if(sccb_tick && sccb_phase == 2'd3) begin


                    //------------------------------------------------
                    // bit_cnt=7
                    //
                    // 说明当前已经发送完第8位
                    //------------------------------------------------
                    if(bit_cnt == 3'd7) begin

                        bit_cnt <= 3'd0;

                        wait_ack <= 1'b1;

                        // 下一阶段等待OV5640返回ACK
                        state <= STATE_ACK;

                    end


                    //------------------------------------------------
                    // 还没有发送完8位
                    //------------------------------------------------
                    else begin

                        // 准备下一个bit
                        bit_cnt <= bit_cnt + 1'b1;

                        // 左移一位
                        //
                        // 例如：
                        //
                        // 01111000
                        // ↓
                        // 11110000
                        //
                        tx_shift <= {tx_shift[6:0], 1'b0};

                    end

                end

            end


            //================================================
            // ACK
            //================================================
            //
            // FPGA在ACK阶段松开SDA。
            //
            // OV5640：
            //
            // SDA=0 → ACK
            // SDA=1 → NACK
            //
            // phase2时SCL为高，而且SDA已经稳定，
            // 因此选择phase2读取cam_sda。
            //================================================
            STATE_ACK: begin

                busy <= 1'b1;


                //------------------------------------------------
                // 读取ACK
                //------------------------------------------------
                if(sccb_tick && sccb_phase == 2'd2) begin

                    if(cam_sda == 1'b0)
                        ack_ok <= 1'b1;      // 收到ACK
                    else
                        ack_ok <= 1'b0;      // 没收到ACK

                end


                //------------------------------------------------
                // ACK的完整时钟周期结束
                //------------------------------------------------
                if(sccb_tick && sccb_phase == 2'd3) begin

                    wait_ack <= 1'b0;


                    //------------------------------------------------
                    // 如果刚才发送的是最后一个字节reg_data
                    //------------------------------------------------
                    if(byte_cnt == 2'd3) begin

                        // 四个字节全部发送完
                        // 开始产生STOP
                        state <= STATE_STOP0;

                    end


                    //------------------------------------------------
                    // 还有下一个字节要发送
                    //------------------------------------------------
                    else begin

                        // 下一个字节重新从bit0计数
                        bit_cnt <= 3'd0;


                        //------------------------------------------------
                        // 根据当前byte_cnt决定：
                        // 下一个tx_shift应该装什么
                        //------------------------------------------------
                        case(byte_cnt)

                            //--------------------------------------------
                            // 当前刚发完8'h78
                            //
                            // 下一字节发送寄存器地址高8位
                            //--------------------------------------------
                            2'd0: begin

                                tx_shift <= reg_addr_latch[15:8];

                                byte_cnt <= 2'd1;

                            end


                            //--------------------------------------------
                            // 当前刚发完寄存器地址高8位
                            //
                            // 下一字节发送寄存器地址低8位
                            //--------------------------------------------
                            2'd1: begin

                                tx_shift <= reg_addr_latch[7:0];

                                byte_cnt <= 2'd2;

                            end


                            //--------------------------------------------
                            // 当前刚发完寄存器地址低8位
                            //
                            // 下一字节发送真正的数据
                            //--------------------------------------------
                            2'd2: begin

                                tx_shift <= reg_data_latch;

                                byte_cnt <= 2'd3;

                            end


                            default: begin

                                tx_shift <= 8'd0;

                            end

                        endcase


                        // 开始发送新的8bit
                        state <= STATE_SEND;

                    end

                end

            end


            //================================================
            // STOP 第1步
            //================================================
            //
            // SCL = 0
            // SDA = 0
            //================================================
            STATE_STOP0: begin

                busy <= 1'b1;

                if(sccb_tick) begin

                    state <= STATE_STOP1;

                end

            end


            //================================================
            // STOP 第2步
            //================================================
            //
            // SCL = 1
            // SDA = 0
            //================================================
            STATE_STOP1: begin

                busy <= 1'b1;

                if(sccb_tick) begin

                    state <= STATE_STOP2;

                end

            end


            //================================================
            // STOP 第3步
            //================================================
            //
            // SCL = 1
            // SDA = 1
            //
            // 因为SCL保持高，
            // SDA从0变成1，
            // 所以产生STOP。
            //================================================
            STATE_STOP2: begin

                busy <= 1'b1;

                if(sccb_tick) begin

                    // 本次写寄存器完成
                    busy <= 1'b0;

                    // done只拉高一个clk
                    done <= 1'b1;

                    // 回到空闲状态
                    state <= STATE_IDLE;

                end

            end


            //================================================
            // 异常情况下回到IDLE
            //================================================
            default: begin

                state <= STATE_IDLE;

                busy <= 1'b0;

            end

        endcase

    end

end


endmodule