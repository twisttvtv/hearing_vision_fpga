`timescale 1ns/1ps

module model_capture #(
    // 0x4300=0x6F 的 OV5640 先输出低字节，在这里恢复标准 RGB565 数值。
    parameter integer LOW_BYTE_FIRST = 1
)(

    input  wire        rst_n,

    // OV5640图像接口
    input  wire        cam_pclk,
    input  wire        cam_vsync,
    input  wire        cam_href,
    input  wire [7:0]  cam_data,

    // RGB565像素
    output reg  [15:0] pixel_data,
    output reg         pixel_valid,

    // 当前像素坐标
    output reg  [11:0] pixel_x,
    output reg  [11:0] pixel_y

);


//============================================================
// 保存RGB565的第一个8bit
//============================================================
reg [7:0] first_byte;


//============================================================
// =0：等待第一个字节
// =1：已经收到第一个字节，等待第二个字节
//============================================================
reg first_byte_received;

//============================================================
// 内部坐标计数器
//============================================================

reg [11:0] x_cnt;

reg [11:0] y_cnt;


//============================================================
// 保存上一拍HREF
//
// 用于检测：
//
// HREF从1变成0
//
// 也就是一行图像结束。
//============================================================

reg href_d;


//============================================================
// 图像采集
//============================================================

always @(posedge cam_pclk or negedge rst_n) begin

    if(!rst_n) begin

        first_byte          <= 8'd0;

        first_byte_received <= 1'b0;

        pixel_data          <= 16'd0;

        pixel_valid         <= 1'b0;


        pixel_x             <= 12'd0;

        pixel_y             <= 12'd0;


        x_cnt               <= 12'd0;

        y_cnt               <= 12'd0;


        href_d              <= 1'b0;

    end


    else begin

        //====================================================
        // 记录上一拍HREF
        //====================================================

        href_d <= cam_href;


        //====================================================
        // pixel_valid默认只保持一个PCLK周期
        //====================================================

        pixel_valid <= 1'b0;


        //====================================================
        // VSYNC高电平
        //
        // 当前配置中VSYNC为高有效。
        //
        // 表示正在进行帧同步，
        // 新的一帧即将开始。
        //
        // 所以坐标全部清零。
        //====================================================

        if(cam_vsync) begin

            first_byte_received <= 1'b0;

            x_cnt <= 12'd0;

            y_cnt <= 12'd0;

        end


        //====================================================
        // HREF = 1
        //
        // 表示当前正在传输一行有效图像数据。
        //====================================================

        else if(cam_href) begin


            //------------------------------------------------
            // 第一个8bit
            //------------------------------------------------

            if(first_byte_received == 1'b0) begin

                first_byte <= cam_data;

                first_byte_received <= 1'b1;

            end


            //------------------------------------------------
            // 第二个8bit
            //
            // 两个字节拼成一个RGB565像素
            //------------------------------------------------

            else begin

                pixel_data <= LOW_BYTE_FIRST ? {cam_data, first_byte}
                                             : {first_byte, cam_data};


                // 当前pixel_data对应的坐标
                pixel_x <= x_cnt;

                pixel_y <= y_cnt;


                // 表示现在输出了一个完整像素
                pixel_valid <= 1'b1;


                // 下一个像素
                x_cnt <= x_cnt + 1'b1;


                // 下一次重新等待第一个字节
                first_byte_received <= 1'b0;

            end

        end


        //====================================================
        // HREF = 0
        //
        // 当前不在一行有效图像中
        //====================================================

        else begin

            // 下一行重新从x=0开始
            x_cnt <= 12'd0;


            // 防止上一行如果字节没有配对完整
            // 影响下一行
            first_byte_received <= 1'b0;


            //================================================
            // 检测HREF下降沿
            //
            // href_d = 1
            // cam_href = 0
            //
            // 表示刚刚结束一整行。
            //
            // 所以y坐标加1。
            //================================================

            if(href_d == 1'b1) begin

                y_cnt <= y_cnt + 1'b1;

            end

            else
            ;

        end

    end

end


endmodule
