// 功能：
// 1. 控制 OV5640 的 RESET 和 PWDN，完成上电时序；
// 2. 通过 model_camera_sccb_write 逐条写入 OV5640 寄存器；
// 3. 先执行基础初始化表，再执行 RGB565 配置表；
// 4. 全部完成后 init_done 保持为 1。
//
// 注意：
// 本模块本身不直接产生 SCL / SDA 波形，
// 它只向 model_camera_sccb_write 提供：
// reg_addr
// reg_data
// sccb_start
// 真正把寄存器数据通过 SCCB 发给 OV5640 的，
// 是 model_camera_sccb_write.v。
//============================================================

`timescale 1ns/1ps

module model_initial #(
    parameter integer CLK_FREQ_HZ = 100_000_000
)(
    input  wire        clk,          // FPGA系统时钟，默认100MHz
    input  wire        rst_n,        // 低电平复位

    //========================================================
    // 与 model_camera_sccb_write 连接
    //========================================================
    input  wire        sccb_busy,    // =1：SCCB模块正在工作
    input  wire        sccb_done,    // =1：一次寄存器写操作完成

    output reg         sccb_start,   // 拉高1拍，启动一次寄存器写操作
    output reg [15:0]  reg_addr,     // 要写的OV5640寄存器地址
    output reg [7:0]   reg_data,     // 要写入寄存器的数据

    //========================================================
    // 直接连接 OV5640
    //========================================================
    output reg         cam_reset,    // OV5640 RESET
    output reg         cam_pwdn,     // OV5640 PWDN

    //========================================================
    // 初始化完成标志
    //========================================================
    output reg         init_done     // =1：OV5640初始化全部完成
);


