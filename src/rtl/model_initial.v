//============================================================
// 6. 初始化主状态机
//============================================================

always @(posedge clk or negedge rst_n) begin

    //--------------------------------------------------------
    // FPGA复位
    //--------------------------------------------------------
    if(!rst_n) begin

        // 从第一个状态开始
        state <= ST_RST_LOW_20MS;

        // 延时计数器清零
        delay_cnt <= 32'd0;

        // 寄存器表索引清零
        table_index <= 8'd0;

        // SCCB控制信号
        sccb_start <= 1'b0;

        reg_addr <= 16'd0;
        reg_data <= 8'd0;

        // OV5640控制
        cam_reset <= 1'b0;

        // 1表示掉电状态
        cam_pwdn <= 1'b1;

        // 初始化还没有完成
        init_done <= 1'b0;

    end


    else begin

        //----------------------------------------------------
        // 默认每个时钟周期先把sccb_start拉低
        //
        // 当真正需要写寄存器时，
        // 某个状态会把它重新拉高。
        //
        // 因此sccb_start只保持一个clk。
        //----------------------------------------------------

        sccb_start <= 1'b0;


        case(state)

            //================================================
            // 状态0：
            //
            // RESET = 0
            // PWDN  = 1
            //
            // 保持20ms
            //
            // 摄像头先保持复位和掉电状态
            //================================================

            ST_RST_LOW_20MS: begin

                init_done <= 1'b0;

                cam_reset <= 1'b0;

                cam_pwdn <= 1'b1;


                if(delay_cnt == DELAY_20MS - 1) begin

                    delay_cnt <= 32'd0;

                    state <= ST_PWDN_LOW_5MS;

                end

                else begin

                    delay_cnt <= delay_cnt + 1'b1;

                end

            end


            //================================================
            // 状态1：
            //
            // RESET = 0
            // PWDN  = 0
            //
            // 摄像头退出掉电模式，
            // 但仍然保持复位。
            //
            // 等待5ms。
            //================================================

            ST_PWDN_LOW_5MS: begin

                cam_reset <= 1'b0;

                cam_pwdn <= 1'b0;


                if(delay_cnt == DELAY_5MS - 1) begin

                    delay_cnt <= 32'd0;

                    state <= ST_RST_HIGH_20MS;

                end

                else begin

                    delay_cnt <= delay_cnt + 1'b1;

                end

            end


            //================================================
            // 状态2：
            //
            // RESET = 1
            // PWDN  = 0
            //
            // 结束硬件复位。
            //
            // 等待20ms，让OV5640稳定。
            //================================================

            ST_RST_HIGH_20MS: begin

                cam_reset <= 1'b1;

                cam_pwdn <= 1'b0;


                if(delay_cnt == DELAY_20MS - 1) begin

                    delay_cnt <= 32'd0;

                    state <= ST_SCCB_WAIT_5MS;

                end

                else begin

                    delay_cnt <= delay_cnt + 1'b1;

                end

            end


            //================================================
            // 状态3：
            //
            // 硬件复位已经结束。
            //
            // 再等待5ms，
            // 然后开始SCCB寄存器配置。
            //================================================

            ST_SCCB_WAIT_5MS: begin

                cam_reset <= 1'b1;

                cam_pwdn <= 1'b0;


                if(delay_cnt == DELAY_5MS - 1) begin

                    delay_cnt <= 32'd0;

                    state <= ST_WRITE_3103;

                end

                else begin

                    delay_cnt <= delay_cnt + 1'b1;

                end

            end


            //================================================
            // 状态4：
            //
            // 写：
            //
            // 0x3103 = 0x11
            //
            // 先判断SCCB是否空闲。
            //================================================

            ST_WRITE_3103: begin

                if(!sccb_busy) begin

                    // 要写的寄存器地址
                    reg_addr <= 16'h3103;

                    // 要写的数据
                    reg_data <= 8'h11;

                    // 命令model_camera_sccb_write开始工作
                    sccb_start <= 1'b1;

                    // 接下来等它写完
                    state <= ST_WAIT_3103;

                end
                else
                ;

            end


            //================================================
            // 状态5：
            //
            // 等待：
            //
            // model_camera_sccb_write
            //
            // 返回：
            //
            // sccb_done = 1
            //================================================

            ST_WAIT_3103: begin

                if(sccb_done) begin

                    state <= ST_WRITE_3008;

                end
                else
                ;

            end


            //================================================
            // 状态6：
            //
            // 写：
            //
            // 0x3008 = 0x82
            //
            // 对OV5640执行软件复位。
            //================================================

            ST_WRITE_3008: begin

                if(!sccb_busy) begin

                    reg_addr <= 16'h3008;

                    reg_data <= 8'h82;

                    sccb_start <= 1'b1;

                    state <= ST_WAIT_3008;

                end
                else
                ;

            end


            //================================================
            // 状态7：
            //
            // 等待软件复位命令发送完成
            //================================================

            ST_WAIT_3008: begin

                if(sccb_done) begin

                    delay_cnt <= 32'd0;

                    state <= ST_SWRESET_10MS;
                end
                else
                ;

            end


            //================================================
            // 状态8：
            //
            // 软件复位以后不能马上写下一条。
            //
            // 等待10ms。
            //================================================

            ST_SWRESET_10MS: begin

                if(delay_cnt == DELAY_10MS - 1) begin

                    delay_cnt <= 32'd0;

                    // 准备从初始化表第0条开始
                    table_index <= 8'd0;

                    state <= ST_UXGA_SEND;

                end

                else begin

                    delay_cnt <= delay_cnt + 1'b1;

                end

            end


            //================================================
            // 状态9：
            //
            // 发送基础初始化表中的一条寄存器。
            //================================================

            ST_UXGA_SEND: begin

                // SCCB空闲以后才能发
                if(!sccb_busy) begin

                    //------------------------------------------------
                    // uxga_word：
                    //
                    // [23:8] = 16bit寄存器地址
                    // [7:0]  = 8bit寄存器数据
                    //------------------------------------------------

                    reg_addr <= uxga_word[23:8];

                    reg_data <= uxga_word[7:0];

                    // 启动SCCB发送
                    sccb_start <= 1'b1;

                    // 等待这一个寄存器写完成
                    state <= ST_UXGA_WAIT;

                end
                else
                ;

            end


            //================================================
            // 状态10：
            //
            // 等待当前基础初始化寄存器写完成。
            //================================================

            ST_UXGA_WAIT: begin

                if(sccb_done) begin

                    //------------------------------------------------
                    // table_index = 206
                    //
                    // 说明第207条已经写完。
                    //------------------------------------------------

                    if(table_index == 8'd206) begin

                        // 基础初始化表结束
                        table_index <= 8'd0;

                        // 接下来配置RGB565
                        state <= ST_RGB_SEND;

                    end


                    else begin

                        // 还没有写完
                        //
                        // 指向下一条寄存器
                        table_index <= table_index + 1'b1;

                        state <= ST_UXGA_SEND;

                    end

                end

            end


            //================================================
            // 状态11：
            //
            // 发送RGB565配置表中的一条寄存器。
            //================================================

            ST_RGB_SEND: begin

                if(!sccb_busy) begin

                    reg_addr <= rgb565_word[23:8];

                    reg_data <= rgb565_word[7:0];

                    sccb_start <= 1'b1;

                    state <= ST_RGB_WAIT;

                end
                else
                ;

            end


            //================================================
            // 状态12：
            //
            // 等待当前RGB565寄存器写完成。
            //================================================

            ST_RGB_WAIT: begin

                if(sccb_done) begin

                    //------------------------------------------------
                    // RGB565表一共45条
                    //
                    // index：
                    // 0 ~ 44
                    //------------------------------------------------

                    if(table_index == 8'd44) begin

                        // 所有寄存器全部写完
                        state <= ST_DONE;

                    end


                    else begin

                        // 指向RGB565表下一条
                        table_index <= table_index + 1'b1;

                        state <= ST_RGB_SEND;

                    end

                end

            end


            //================================================
            // 状态13：
            //
            // OV5640初始化完成
            //================================================

            ST_DONE: begin

                // 初始化完成以后一直保持1
                init_done <= 1'b1;

                // OV5640保持正常工作状态
                cam_reset <= 1'b1;

                cam_pwdn <= 1'b0;

                // 永远停在这个状态
                state <= ST_DONE;

            end


            //================================================
            // 异常保护
            //
            // 如果state跑到非法状态，
            // 就重新从初始化开始。
            //================================================

            default: begin

                state <= ST_RST_LOW_20MS;

                delay_cnt <= 32'd0;

                table_index <= 8'd0;

                sccb_start <= 1'b0;

                cam_reset <= 1'b0;

                cam_pwdn <= 1'b1;

                init_done <= 1'b0;

            end

        endcase

    end

end


